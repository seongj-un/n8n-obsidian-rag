"""현재 n8n Answer 노드의 프롬프트를 문자 그대로 재현한 것."""
FEWSHOT = """[아래는 좋은 답변의 예시입니다. 이 형식과 이 정도의 상세함을 그대로 따라하세요]

질문: 캐시가 뭐야?
답변:
캐시는 자주 쓰는 데이터를 더 빠른 저장소에 미리 두어 접근 속도를 높이는 기법입니다.

- **캐시 히트**: 원하는 데이터가 캐시에 있어 원본까지 가지 않고 즉시 응답한다. 히트율이 캐시 성능을 좀우하는 핵심 지표다.
- **캐시 미스**: 캐시에 없어 원본 저장소까지 접근한 뒤, 보통 그 결과를 캐시에 채워 넣어 다음 요청에 대비한다.
- **지역성**: 최근 쓴 데이터가 또 쓰이고(시간 지역성), 근처 데이터가 함께 쓰인다는(공간 지역성) 전제 위에서 동작한다.
- **무효화 전략**: TTL로 일정 시간 뒤 만료시키거나, LRU로 오래 안 쓴 항목부터 밀어낸다.
- **쓰기 정책**: write-through는 원본과 캐시를 함께 써서 안전하지만 느리고, write-back은 캐시에 먼저 써서 빠르지만 유실 위험이 있다.
- 💡 **주의**: 히트율이 낮으면 조회 비용만 늘어 오히려 손해다. 원본이 바뎀는데 캐시가 남아 있으면 정합성이 깨진다."""

FORMAT = """[형식 규칙]
- 첫 줄은 핵심 한 문장, 굵게 표시하지 말 것
- 빈 줄 뒤 - 로 시작하는 불릿 5~8개
- 모든 불릿은 (- **용어**: 설명) 형태로 용어만 굵게
- 각 불릿의 설명은 한~두 문장으로 구체적으로 (100자 내외)
- 노트에 트레이드오프·주의점·실무 팁이 있으면 마지막에 (- 💡 **주의**: ...) 불릿을 1~2개 추가
- 전체 1500자 이내
- 출처나 파일명은 쓰지 말 것 (시스템이 자동으로 붙임)"""

def build(question, docs):
    ctx = "\n\n---\n\n".join(
        "[출처: " + ((d.get("metadata") or {}).get("source") or "알 수 없음") + "]\n" + (d.get("text") or "")
        for d in docs)
    return ("다음은 사용자의 Obsidian 노트에서 검색된 내용입니다.\n\n" + ctx +
        "\n\n=====\n[근거 규칙]\n- 위 검색된 노트 내용만 근거로 답하세요. 추측 금지.\n"
        "- 노트에 있는 내용은 최대한 풍부하게 담으세요. 짧게 요약해버리지 말 것.\n"
        "- 근거가 없으면 (노트에서 관련 내용을 찾지 못했어요) 라고만 답하세요.\n\n"
        + FEWSHOT + "\n\n" + FORMAT + "\n\n=====\n질문: " + question + "\n답변:")
